export type TranslationKey = keyof typeof messages["zh-CN"];

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: MessageValues) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const fallbackI18n: I18nContextValue = {
  locale: DEFAULT_LOCALE,
  setLocale: () => undefined,
  t: (key, values) => interpolate(messages[DEFAULT_LOCALE][key], values),
};

function initialLocale(): Locale {
  const stored = typeof localStorage === "undefined" ? null : readStoredLocale(localStorage);
  const browserLocale = typeof navigator === "undefined" ? null : navigator.language;
  return detectLocale(stored, browserLocale);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  const setLocale = (next: Locale) => {
    setLocaleState(next);
    if (typeof localStorage !== "undefined") writeStoredLocale(localStorage, next);
  };
  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t: (key, values) => interpolate(messages[locale][key] ?? messages[DEFAULT_LOCALE][key], values),
  }), [locale]);
  useEffect(() => {
    document.documentElement.lang = locale;
    window.api?.settings?.setLocale?.(locale);
  }, [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  return context ?? fallbackI18n;
}

export function useOptionalI18n(): I18nContextValue | null {
  return useContext(I18nContext);
}
